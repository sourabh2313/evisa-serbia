// Authentication Handlers
async function handleLoginSubmit(e) {
  if (e) e.preventDefault();
  
  const emailInput = document.getElementById('login-email');
  const mobEmailInput = document.getElementById('login-email-mob');
  const passInput = document.getElementById('login-password');
  
  let emailVal = (emailInput && emailInput.value && emailInput.value.trim()) || 
                 (mobEmailInput && mobEmailInput.value && mobEmailInput.value.trim()) || '';
  let passVal = passInput ? passInput.value : '';

  if (!emailVal || !passVal) {
    showToast('Please enter both username/email and password.', 'error');
    if (!emailVal && emailInput) emailInput.focus();
    else if (!passVal && passInput) passInput.focus();
    return;
  }

  // 1. Check server database via API if available
  try {
    const res = await fetch('/api/auth/login', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ email: emailVal, password: passVal })
    });
    const data = await res.json();
    if (data && data.success && data.user) {
      const authUser = {
        name: data.user.name,
        email: data.user.email,
        passportNumber: data.user.passportNumber || 'N12345678',
        citizenship: data.user.citizenship || 'India'
      };
      localStorage.setItem('srb_evisa_auth_user', JSON.stringify(authUser));
      closeModal('login-modal');
      showToast(`Signed in successfully as ${authUser.name}`);
      const nextUrl = getAuthRedirectUrl();
      triggerBuffering(() => {
        window.location.href = nextUrl;
      }, 400);
      setTimeout(() => {
        window.location.href = nextUrl;
      }, 500);
      return;
    } else if (data && data.success === false) {
      showToast(data.message || 'Invalid username or password. The details provided do not match.', 'error');
      if (passInput) {
        passInput.value = '';
        passInput.focus();
      }
      return;
    }
  } catch (err) {}

  // 2. Check local registered users (for offline / file:// mode)
  const regUser = findRegisteredUser(emailVal);
  if (regUser) {
    if (regUser.password !== passVal) {
      showToast('Invalid username or password. Details do not match registered user.', 'error');
      if (passInput) {
        passInput.value = '';
        passInput.focus();
      }
      return;
    }

    const authUser = {
      name: regUser.name,
      email: regUser.email,
      passportNumber: regUser.passportNumber || 'A123456',
      citizenship: regUser.citizenship || 'India'
    };
    localStorage.setItem('srb_evisa_auth_user', JSON.stringify(authUser));

    closeModal('login-modal');
    showToast(`Signed in successfully as ${authUser.name}`);
    const nextUrl = getAuthRedirectUrl();
    triggerBuffering(() => {
      window.location.href = nextUrl;
    }, 400);
    setTimeout(() => {
      window.location.href = nextUrl;
    }, 500);
    return;
  }

  // 3. Check static pre-existing users (for offline mode)
  const staticUsers = [
    { email: 'rahul.rana@gmail.com', password: 'password123', name: 'Rahul Rana', passportNumber: 'N12345678', citizenship: 'United States' },
    { email: 'karan.nagpal@gmail.com', password: 'password123', name: 'KARAN NAGPAL', passportNumber: 'K9876543', citizenship: 'India' },
    { email: 'rana09299@gmail.com', password: 'Rahul@123', name: 'RAHUL BHARDWAJ', passportNumber: 'D2345678', citizenship: 'India' }
  ];

  const matchedStatic = staticUsers.find(u => {
    const handle = u.email.split('@')[0].toLowerCase();
    const clean = emailVal.toLowerCase().trim();
    return (u.email.toLowerCase() === clean || handle === clean) && u.password === passVal;
  });

  if (matchedStatic) {
    const authUser = {
      name: matchedStatic.name,
      email: matchedStatic.email,
      passportNumber: matchedStatic.passportNumber,
      citizenship: matchedStatic.citizenship
    };
    localStorage.setItem('srb_evisa_auth_user', JSON.stringify(authUser));
    closeModal('login-modal');
    showToast(`Signed in successfully as ${authUser.name}`);
    const nextUrl = getAuthRedirectUrl();
    triggerBuffering(() => {
      window.location.href = nextUrl;
    }, 400);
    setTimeout(() => {
      window.location.href = nextUrl;
    }, 500);
    return;
  }

  // 4. Invalid credentials error:
  showToast('Invalid username or password. The details provided do not match any registered account.', 'error');
  if (passInput) {
    passInput.value = '';
    passInput.focus();
  }
}

async function handleRegisterSubmit(e) {
  if (e) e.preventDefault();
  
  const firstNameInput = document.getElementById('reg-name');
  const lastNameInput = document.getElementById('reg-surname');
  const emailInput = document.getElementById('reg-email');
  const passInput = document.getElementById('reg-password');
  const passConfirmInput = document.getElementById('reg-password-confirm');
  const termsCheckbox = document.getElementById('reg-terms') || document.querySelector('#register-form input[type="checkbox"][required]');

  const firstName = firstNameInput ? firstNameInput.value.trim() : '';
  const lastName = lastNameInput ? lastNameInput.value.trim() : '';
  const email = emailInput ? emailInput.value.trim() : '';
  const password = passInput ? passInput.value : '';
  const passwordConfirm = passConfirmInput ? passConfirmInput.value : '';
  const passport = document.getElementById('reg-passport')?.value?.trim() || 'A123456';
  const citizenship = document.getElementById('reg-citizenship')?.value || 'India';
  const docType = document.getElementById('reg-doc-type')?.value || 'Passport';

  // 1. Normal field validation
  if (!firstName) {
    showToast('Please enter your first name.', 'error');
    if (firstNameInput) firstNameInput.focus();
    return;
  }

  if (!lastName) {
    showToast('Please enter your last name.', 'error');
    if (lastNameInput) lastNameInput.focus();
    return;
  }

  if (!email || !email.includes('@')) {
    showToast('Please enter a valid email address.', 'error');
    if (emailInput) emailInput.focus();
    return;
  }

  if (!password) {
    showToast('Please enter a password.', 'error');
    if (passInput) passInput.focus();
    return;
  }

  // 2. Normal validation: check matching passwords
  if (password !== passwordConfirm) {
    showToast('Passwords do not match. Please verify your password.', 'error');
    if (passConfirmInput) {
      passConfirmInput.focus();
      passConfirmInput.select();
    }
    return;
  }

  if (termsCheckbox && !termsCheckbox.checked) {
    showToast('Please agree to the Terms of Use to proceed.', 'error');
    termsCheckbox.focus();
    return;
  }

  // 3. User created and registered
  const fullName = `${firstName} ${lastName}`.trim().toUpperCase();
  const newUser = {
    name: fullName,
    firstName: firstName,
    lastName: lastName,
    email: email,
    password: password,
    passportNumber: passport,
    citizenship: citizenship,
    docType: docType
  };

  // 4. Save to registered users dictionary (with email and username keys for lookup)
  try {
    const regUsers = JSON.parse(localStorage.getItem('srb_registered_users') || '{}');
    regUsers[email.toLowerCase()] = newUser;
    if (email.includes('@')) {
      regUsers[email.split('@')[0].toLowerCase()] = newUser;
    }
    localStorage.setItem('srb_registered_users', JSON.stringify(regUsers));
  } catch (err) {}

  // 5. Sync with backend API if online
  try {
    fetch('/api/auth/register', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        email: email,
        password: password,
        name: fullName,
        passportNumber: passport,
        citizenship: citizenship
      })
    }).catch(() => {});
  } catch (err) {}

  // 6. Set active authenticated session as this user
  localStorage.setItem('srb_evisa_auth_user', JSON.stringify({
    name: fullName,
    email: email,
    passportNumber: passport,
    citizenship: citizenship
  }));

  // 7. Keep login form fields clear
  const loginEmail = document.getElementById('login-email');
  const loginPass = document.getElementById('login-password');
  const mobEmail = document.getElementById('login-email-mob');
  if (loginEmail) loginEmail.value = '';
  if (loginPass) loginPass.value = '';
  if (mobEmail) mobEmail.value = '';

  // 8. Close register modal, show confirmation, and redirect directly to next page
  closeModal('register-modal');
  showToast(`User ${fullName} registered successfully! Redirecting...`);

  const nextUrl = getAuthRedirectUrl();
  triggerBuffering(() => {
    window.location.href = nextUrl;
  }, 400);

  setTimeout(() => {
    window.location.href = nextUrl;
  }, 500);
}

// Multi-Step Form Wizard Logic
function startNewApplication() {
  if (!currentUser) {
    openLoginModal();
    return;
  }
  currentWizardStep = 1;
  updateWizardUI();
  openModal('wizard-modal');

  // Pre-fill user data if available
  if (currentUser && currentUser.name) {
    const parts = currentUser.name.split(' ');
    const surEl = document.getElementById('field-surname');
    const givEl = document.getElementById('field-givenName');
    const surname = parts.length > 1 ? parts.pop() : '';
    const givenName = parts.join(' ') || currentUser.name;
    if (surEl) surEl.value = surname;
    if (givEl) givEl.value = givenName;
  }
  if (currentUser && currentUser.passportNumber) {
    const passEl = document.getElementById('field-passportNumber');
    if (passEl) passEl.value = currentUser.passportNumber;
  }
}

function wizardNavigate(direction) {
  if (direction === 1) {
    if (!validateCurrentStep(currentWizardStep)) return;
    if (currentWizardStep < 8) currentWizardStep++;
  } else if (direction === -1) {
    if (currentWizardStep > 1) currentWizardStep--;
  }
  updateWizardUI();
}

function validateCurrentStep(step) {
  const currentPane = document.getElementById(`step-pane-${step}`);
  const requiredInputs = currentPane.querySelectorAll('[required]');
  for (let input of requiredInputs) {
    if (!input.value || (input.type === 'checkbox' && !input.checked)) {
      input.focus();
      showToast('Please complete all required fields (*)', 'error');
      return false;
    }
  }
  return true;
}

function updateWizardUI() {
  // Hide all step panes
  for (let i = 1; i <= 8; i++) {
    const pane = document.getElementById(`step-pane-${i}`);
    const indicator = document.getElementById(`step-indicator-${i}`);
    if (pane) pane.style.display = (i === currentWizardStep) ? 'block' : 'none';
    if (indicator) {
      indicator.classList.remove('active', 'completed');
      if (i === currentWizardStep) indicator.classList.add('active');
      if (i < currentWizardStep) indicator.classList.add('completed');
    }
  }

  // Prev / Next button visibility
  const prevBtn = document.getElementById('wizard-prev-btn');
  const nextBtn = document.getElementById('wizard-next-btn');
  const submitBtn = document.getElementById('wizard-submit-btn');

  prevBtn.style.visibility = (currentWizardStep === 1) ? 'hidden' : 'visible';

  if (currentWizardStep === 8) {
    nextBtn.style.display = 'none';
    submitBtn.style.display = 'inline-block';
    renderReviewSummary();
  } else {
    nextBtn.style.display = 'inline-block';
    submitBtn.style.display = 'none';
  }
}

