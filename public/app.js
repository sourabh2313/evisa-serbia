// Set Language Function
function setLanguage(lang) {
  currentLang = lang;
  document.querySelectorAll('.app-header__menu__language a').forEach(a => a.classList.remove('active'));
  const activeBtn = document.getElementById(`lang-${lang}`);
  if (activeBtn) activeBtn.classList.add('active');

  const dict = i18n[lang] || i18n.eng;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });
}

// Helper to find a registered user by email or username
function findRegisteredUser(idOrEmail) {
  if (!idOrEmail) return null;
  const clean = idOrEmail.trim().toLowerCase();
  try {
    const regUsers = JSON.parse(localStorage.getItem('srb_registered_users') || '{}');
    if (regUsers[clean]) return regUsers[clean];
    for (const key of Object.keys(regUsers)) {
      const u = regUsers[key];
      if (u) {
        if (key.toLowerCase() === clean) return u;
        if (u.email && u.email.toLowerCase() === clean) return u;
        if (u.email && u.email.split('@')[0].toLowerCase() === clean) return u;
        if (clean.includes('@') && u.email && u.email.toLowerCase() === clean) return u;
      }
    }
  } catch (e) {}
  return null;
}

// Dynamic User Name Resolution
function resolveUserName(input) {
  if (!input || !input.trim()) {
    return 'Rahul Rana';
  }
  const cleanInput = input.trim();
  if (cleanInput.toLowerCase().includes('rahul') || cleanInput.toLowerCase().includes('rana') || cleanInput.toLowerCase().includes('raha')) {
    return 'Rahul Rana';
  }

  // Check if matches a registered user in localStorage
  const regUser = findRegisteredUser(cleanInput);
  if (regUser && regUser.name) {
    return regUser.name;
  }

  // If input contains '@', extract the username portion
  let rawName = cleanInput;
  if (cleanInput.includes('@')) {
    rawName = cleanInput.split('@')[0];
  }

  // Replace delimiters with spaces and clean up
  let formatted = rawName.replace(/[._\-+]/g, ' ').replace(/\s+/g, ' ').trim();
  if (!formatted || formatted.toUpperCase() === 'JOHN DOE' || formatted.toUpperCase() === 'APPLICANT') return 'Rahul Rana';

  return formatted.split(' ').map(w => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join(' ');
}

