// Toast System
function showToast(message, type = 'success') {
  let toast = document.getElementById('toast') || document.getElementById('app-toast');
  if (!toast) return;

  let msgEl = document.getElementById('toast-message');
  let icon = document.getElementById('toast-icon');

  if (!msgEl) {
    toast.innerHTML = `<i class="fa-solid fa-circle-check" id="toast-icon" style="margin-right: 8px;"></i><span id="toast-message">${message}</span>`;
    msgEl = document.getElementById('toast-message');
    icon = document.getElementById('toast-icon');
  } else {
    msgEl.textContent = message;
  }

  if (icon) {
    if (type === 'error') {
      icon.className = 'fa-solid fa-circle-exclamation';
      toast.style.backgroundColor = '#dc2626';
    } else {
      icon.className = 'fa-solid fa-circle-check';
      toast.style.backgroundColor = '#253956';
    }
  }

  toast.classList.add('show');
  setTimeout(() => {
    toast.classList.remove('show');
  }, 4000);
}
